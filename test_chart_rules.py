CFG = r.merged()


def candles(closes, last=None):
    """종가 열로 일봉. 시가·고가·저가는 종가와 같게 둬서 꼬리가 없다. last 로 마지막 봉을 덮는다."""
    out = [{"date": f"d{i:03d}", "open": c, "high": c, "low": c, "close": c}
           for i, c in enumerate(closes)]
    if last:
        out[-1].update(last)
    return out


def rising(n, lo=8_000.0, hi=10_000.0):
    return [lo + (hi - lo) * i / (n - 1) for i in range(n)]


def kinds(cs, **over):
    return [(h["kind"], h.get("ma_days")) for h in r.detect(cs, r.merged(over))]


class Pullback(unittest.TestCase):
    # 130봉 우상향 뒤 20일선 근처로 눌렸다 돌아선 모양. 5>20>60 정배열이 산다.
    base = rising(126, 6_000, 10_000) + [10_050, 9_900, 9_800, 9_950]

    def at(self, pct):
        """마지막 봉을 20일선 대비 pct% 자리에 둔다 (마지막 봉도 20일선 평균에 들어간다)."""
        s19 = sum(self.base[-20:-1])
        k = 1 + pct / 100
        return self.base[:-1] + [k * s19 / (20 - k)]

    def test_띠_안이면_20일_눌림(self):
        self.assertIn((r.PULLBACK, 20), kinds(candles(self.base)))

    def test_상한은_5퍼센트(self):
        self.assertIn((r.PULLBACK, 20), kinds(candles(self.at(4.9)), new_high_days=999))
        self.assertNotIn((r.PULLBACK, 20), kinds(candles(self.at(5.2)), new_high_days=999))

    def test_윗꼬리면_눌림_제외(self):
        c = self.base[-1]
        cs = candles(self.base, last={"open": c, "high": c * 1.05, "low": c})
        self.assertEqual(r.wick(cs[-1], CFG), "upper")
        self.assertNotIn((r.PULLBACK, 20), kinds(cs))

    def test_아랫꼬리면_상한_7퍼센트(self):
        closes = self.at(6.0)                     # 5% 밖, 7% 안
        top = closes[-1]
        plain = candles(closes)
        lower = candles(closes, last={"open": top, "high": top, "low": top * 0.95})
        self.assertEqual(r.wick(lower[-1], CFG), "lower")
        self.assertNotIn((r.PULLBACK, 20), kinds(plain, new_high_days=999))
        self.assertIn((r.PULLBACK, 20), kinds(lower, new_high_days=999))

    def test_꼬리는_몸통과_2퍼센트를_둘_다_넘어야(self):
        # 몸통 0 짜리 도지에 1% 꼬리 -- 몸통 조건은 넘지만 2% 에 못 미친다.
        c = {"open": 10_000, "high": 10_100, "low": 10_000, "close": 10_000}
        self.assertIsNone(r.wick(c, CFG))
        # 2.5% 꼬리지만 몸통이 3% -- 2% 는 넘지만 몸통에 못 미친다.
        c = {"open": 10_000, "high": 10_550, "low": 10_000, "close": 10_300}
        self.assertIsNone(r.wick(c, CFG))

    def test_내려오는_차트는_제외(self):
        # 직전 2일 평균(9,850)과 전일(9,800) 둘 다 아래.
        closes = self.base[:-1] + [9_750]
        self.assertTrue(r.is_falling(closes, CFG))
        self.assertEqual([k for k, _ in kinds(candles(closes))], [])

    def test_전일보다_오르면_평균_아래여도_내려오는_차트가_아니다(self):
        # 2026-10-17: 급락 다음 날 반등한 첫날(피노 10/16). 2일 평균 9,850 아래지만
        # 전일 9,800 보다 높다.
        closes = self.base[:-1] + [9_820]
        self.assertFalse(r.is_falling(closes, CFG))
        self.assertIn((r.PULLBACK, 20), kinds(candles(closes)))

    def test_평균보다_높으면_전일보다_낮아도_내려오는_차트가_아니다(self):
        closes = self.base[:-2] + [9_700, 9_950, 9_900]   # 평균 9,825 < 9,900 < 전일 9,950
        self.assertFalse(r.is_falling(closes, CFG))


class Reclaim(unittest.TestCase):
    # 긴 우상향(20>60>120) 뒤 20일선 아래로 잠깐 눌렸다가 선 바로 밑에서 오르는 모양.
    def shape(self, d1, d0):
        closes = rising(130, 5_000, 10_000) + [9_700, 9_400, 9_300]
        closes.append(closes[-1] * (1 + d1 / 100))
        closes.append(closes[-1] * (1 + d0 / 100))
        return closes

    def test_이틀_상승이면_회복(self):
        closes = self.shape(+1.5, +1.5)
        hit = r.reclaim(candles(closes), CFG)
        self.assertIsNotNone(hit)
        self.assertLessEqual(hit["gap"], 0.0)

    def test_전날_보합이어도_회복(self):
        self.assertIsNotNone(r.reclaim(candles(self.shape(-0.3, +3.0)), CFG))

    def test_전날이_보합보다_밀렸으면_아님(self):
        self.assertIsNone(r.reclaim(candles(self.shape(-1.5, +3.0)), CFG))

    def test_오늘_보합이면_아님(self):
        self.assertIsNone(r.reclaim(candles(self.shape(+1.5, 0.0)), CFG))

    def test_120일선_정배열이_아니면_아님(self):
        closes = [12_000] * 60 + rising(75, 8_000, 10_000) + [9_700, 9_400, 9_300]
        closes += [closes[-1] * 1.015, closes[-1] * 1.015 ** 2]
        self.assertIsNone(r.reclaim(candles(closes), CFG))


class Breakout(unittest.TestCase):
    def test_완만한_신고가(self):
        self.assertEqual(kinds(candles([10_000] * 129 + [10_500]))[0][0], r.BREAKOUT)

    def test_과열_신고가는_빠진다(self):
        # 20봉에 두 배: 20일선 +31% (컷 25)
        closes = [10_000] * 110 + [10_000 + 500 * i for i in range(1, 21)]
        cs = candles(closes)
        hot = r.overextension(cs, CFG)
        self.assertEqual(hot["ma_days"], 20)
        self.assertNotIn(r.BREAKOUT, [k for k, _ in kinds(cs)])

    def test_하루_급등은_5일선으로_걸린다(self):
        # 하루 +20%: 5일선 +15.4% (컷 15), 20일선 +18.8% (컷 25 안)
        cs = candles([10_000] * 129 + [12_000])
        hot = r.overextension(cs, CFG)
        self.assertEqual((hot["ma_days"], hot["cut"]), (5, 15.0))
        self.assertNotIn(r.BREAKOUT, [k for k, _ in kinds(cs)])

    def test_60일선에서_멀어도_단기선_안이면_신고가(self):
        # 2026-10-22 사용자 결정: 60일선 이격은 보지 않는다. 하루 1.5% 씩 130봉 꾸준히
        # 오른 모양은 60일선 +50% 가 넘지만 20일선 +15%·5일선 +3% 안팎이라 통과한다.
        closes = [5_000 * 1.015 ** i for i in range(130)]
        cs = candles(closes)
        self.assertGreater(closes[-1] / (sum(closes[-60:]) / 60) - 1, 0.30)
        self.assertIsNone(r.overextension(cs, CFG))
        self.assertEqual(kinds(cs)[0][0], r.BREAKOUT)

    def test_선을_모르면_막지_않는다(self):
        # 봉이 모자라 그 선이 없으면 과열로 치지 않는다 -- 신규 상장주가 영영 못 든다.
        cs = candles([10_000] * 39 + [10_300])
        got = r.overextension(cs, r.merged({"max_breakout_gap": {"5": 15.0, "200": 1.0}}))
        self.assertIsNone(got)


